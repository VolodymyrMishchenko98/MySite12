function initHeroParticles() {
  const canvas = document.getElementById("hero-canvas");
  const heroSection = document.getElementById("hero");
  if (!canvas || !heroSection) return;

  const desktopMotion = window.matchMedia(
    "(min-width: 901px) and (prefers-reduced-motion: no-preference)",
  );
  if (!desktopMotion.matches) {
    desktopMotion.addEventListener(
      "change",
      (event) => {
        if (event.matches) initHeroParticles();
      },
      { once: true },
    );
    return;
  }

  const ctx = canvas.getContext("2d");
  let particles = [];
  const mouse = { x: null, y: null, radius: 150 };

  // Оптимизация: запускаем только когда канвас виден
  const observer = new IntersectionObserver(
    (entries) => {
      entries[0].isIntersecting ? startAnim() : stopAnim();
    },
    { threshold: 0.1 },
  );
  observer.observe(canvas);

  let animationId;
  function resize() {
    canvas.width = heroSection.offsetWidth;
    canvas.height = heroSection.offsetHeight;
    init();
  }

  heroSection.addEventListener("mousemove", (e) => {
    const rect = canvas.getBoundingClientRect();
    mouse.x = e.clientX - rect.left;
    mouse.y = e.clientY - rect.top;
  });

  heroSection.addEventListener("mouseleave", () => {
    mouse.x = null;
    mouse.y = null;
  });

  class Particle {
    constructor(x, y, dx, dy, size, color) {
      this.x = x;
      this.y = y;
      this.dx = dx;
      this.dy = dy;
      this.size = size;
      this.color = color;
    }

    draw() {
      ctx.beginPath();
      ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2, false);
      ctx.fillStyle = this.color;
      ctx.fill();
    }

    update() {
      if (this.x > canvas.width || this.x < 0) this.dx = -this.dx;
      if (this.y > canvas.height || this.y < 0) this.dy = -this.dy;

      let dx = mouse.x - this.x;
      let dy = mouse.y - this.y;
      let distance = Math.sqrt(dx * dx + dy * dy);

      if (distance < mouse.radius && mouse.x !== null) {
        if (mouse.x < this.x && this.x < canvas.width - this.size * 10)
          this.x += 1.5;
        if (mouse.x > this.x && this.x > this.size * 10) this.x -= 1.5;
        if (mouse.y < this.y && this.y < canvas.height - this.size * 10)
          this.y += 1.5;
        if (mouse.y > this.y && this.y > this.size * 10) this.y -= 1.5;
      }

      this.x += this.dx;
      this.y += this.dy;
      this.draw();
    }
  }

  window.addEventListener("resize", resize);
  resize();

  function init() {
    particles = [];
    const count = (canvas.width * canvas.height) / 10000;
    for (let i = 0; i < count; i++) {
      let size = Math.random() * 2 + 0.5;
      let x = Math.random() * (canvas.width - size * 2) + size;
      let y = Math.random() * (canvas.height - size * 2) + size;
      let dx = Math.random() * 0.4 - 0.2;
      let dy = Math.random() * 0.4 - 0.2;
      particles.push(
        new Particle(x, y, dx, dy, size, "rgba(99, 102, 241, 0.9)"),
      );
    }
  }

  function connect() {
    for (let a = 0; a < particles.length; a++) {
      for (let b = a; b < particles.length; b++) {
        let dx = particles[a].x - particles[b].x;
        let dy = particles[a].y - particles[b].y;
        let distance = Math.sqrt(dx * dx + dy * dy);
        if (distance < 100) {
          ctx.strokeStyle = `rgba(99, 102, 241, ${1 - distance / 100})`;
          ctx.lineWidth = 1;
          ctx.beginPath();
          ctx.moveTo(particles[a].x, particles[a].y);
          ctx.lineTo(particles[b].x, particles[b].y);
          ctx.stroke();
        }
      }
    }
  }

  function startAnim() {
    if (!animationId) animate();
  }
  function stopAnim() {
    cancelAnimationFrame(animationId);
    animationId = null;
  }

  function animate() {
    animationId = requestAnimationFrame(animate);
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    particles.forEach((p) => p.update());
    connect();
  }
}

