function syncMobileMenuState(isOpen) {
  document.body.classList.toggle("mobile-menu-open", isOpen);
  mobBtn.setAttribute("aria-label", isOpen ? "Close menu" : "Open menu");

  const mainNav = document.getElementById("main-nav");
  const menu = document.getElementById("mobile-menu");

  if (mainNav && menu) {
    const rect = mainNav.getBoundingClientRect();
    // Вычитаем 1px, чтобы меню "заходило" на границу хедера, создавая бесшовный стык
    menu.style.top = rect.bottom - 1 + "px";
    menu.style.left = rect.left + "px";
    menu.style.width = rect.width + "px";
  }

  if (mobBackdrop) {
    if (isOpen) {
      mobBackdrop.classList.remove("hidden");
      mobBackdrop.classList.add("backdrop-visible");
    } else {
      mobBackdrop.classList.add("hidden");
      mobBackdrop.classList.remove("backdrop-visible");
    }
  }
}

// Update menu position on resize when menu is open
window.addEventListener("resize", () => {
  if (document.body.classList.contains("mobile-menu-open")) {
    syncMobileMenuState(true);
  }
});

function closeMenu(menu, button) {
  menu.classList.add("menu-hidden");
  menu.classList.remove("menu-visible");
  button.setAttribute("aria-expanded", "false");

  if (menu === mobMenu) syncMobileMenuState(false);
}

function toggleMenu(menu, button) {
  const isHidden = menu.classList.toggle("menu-hidden");
  menu.classList.toggle("menu-visible", !isHidden);
  button.setAttribute("aria-expanded", String(!isHidden));

  if (menu === mobMenu) syncMobileMenuState(!isHidden);
}

