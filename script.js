const heightVal = document.getElementById("calc-height-val");
const weightVal = document.getElementById("calc-weight-val");
const resultBmiStatus = document.getElementById("result-bmi-status");

function calculateFitness() {
  const height = parseInt(heightInput.value);
  const weight = parseInt(weightInput.value);

  if (heightVal) heightVal.textContent = height;
  if (weightVal) weightVal.textContent = weight;

  const heightInMeters = height / 100;
  const bmi = (weight / (heightInMeters * heightInMeters)).toFixed(1);

  if (resultBmi) {
    if (resultBmi.textContent !== bmi) {
      resultBmi.textContent = bmi;
      resultBmi.classList.add("scale-110", "opacity-80");
      setTimeout(
        () => resultBmi.classList.remove("scale-110", "opacity-80"),
        100,
      );
    }
  }

  const currentLang = document.documentElement.lang || "uk";
  const dictKey = currentLang === "uk" ? "ua" : "en";
  let statusText = "";
  let statusClass =
    "text-[11px] font-bold uppercase tracking-wider mt-0.5 transition-all duration-500 ";

  if (bmi < 18.5) {
    statusText = tr[dictKey]["bmi-low"];
    statusClass += "text-yellow-500";
  } else if (bmi >= 18.5 && bmi < 25) {
    statusText = tr[dictKey]["bmi-normal"];
    statusClass += "text-green-500";
  } else if (bmi >= 25 && bmi < 30) {
    statusText = tr[dictKey]["bmi-warn"];
    statusClass += "text-orange-400";
  } else {
    statusText = tr[dictKey]["bmi-danger"];
    statusClass += "text-red-500";
  }

  if (resultBmiStatus) {
    resultBmiStatus.textContent = statusText;
    resultBmiStatus.className = statusClass;
  }

  const baseCalories = Math.round((10 * weight + 6.25 * height - 125) * 1.375);
  if (resultCalories) {
    if (resultCalories.textContent !== String(baseCalories)) {
      resultCalories.textContent = baseCalories;
      resultCalories.classList.add("scale-110", "opacity-80");
      setTimeout(
        () => resultCalories.classList.remove("scale-110", "opacity-80"),
        100,
      );
    }
  }
}

