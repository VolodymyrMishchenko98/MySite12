function setLanguage(lang, animate = true) {
  const selectedLang = tr[lang] ? lang : "ua";
  const elements = document.querySelectorAll(".i18n");

  const updateText = () => {
    localStorage.setItem("lang", selectedLang);
    document.documentElement.lang = selectedLang === "ua" ? "uk" : "en";
    elements.forEach((el) => {
      const key = el.dataset.key;
      if (tr[selectedLang][key]) el.innerHTML = tr[selectedLang][key];
    });
    document
      .querySelectorAll("[data-ua-alt][data-en-alt]")
      .forEach((image) => {
        image.alt = image.dataset[`${selectedLang}Alt`];
      });
    document.querySelectorAll(".lang-btn").forEach((el) => {
      const isSelected = el.dataset.lang === selectedLang;
      el.classList.toggle("text-indigo-500", isSelected);
      el.setAttribute("aria-pressed", String(isSelected));
    });
    refreshMagneticButtonRects();
    makeCodeCopyable();
  };

  if (!animate) {
    updateText();
    return;
  }

  elements.forEach((el) => el.classList.add("i18n-changing"));
  window.setTimeout(() => {
    updateText();
    elements.forEach((el) => el.classList.remove("i18n-changing"));
  }, 120);
}

